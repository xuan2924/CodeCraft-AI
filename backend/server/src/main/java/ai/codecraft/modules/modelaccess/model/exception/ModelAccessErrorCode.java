package ai.codecraft.modules.modelaccess.model.exception;

import ai.codecraft.common.exception.ErrorCode;

public enum ModelAccessErrorCode implements ErrorCode {
    MODEL_INVALID_REQUEST(400), MODEL_ENCRYPTION_UNAVAILABLE(503), MODEL_CREDENTIAL_UNAVAILABLE(503),
    MODEL_CONNECTION_NOT_FOUND(404), MODEL_NAME_CONFLICT(409), MODEL_IDEMPOTENCY_CONFLICT(409),
    MODEL_VERSION_CONFLICT(409), MODEL_RECEIPT_EXPIRED(410), MODEL_CONFIGURATION_NOT_FOUND(404), MODEL_STORAGE_UNAVAILABLE(503), MODEL_PROTOCOL_UNSUPPORTED(422), MODEL_REQUEST_TIMEOUT(504), MODEL_INVALID_RESPONSE(502), MODEL_OUTPUT_LIMIT_EXCEEDED(422), MODEL_REDIRECT_REJECTED(502), MODEL_AUTHENTICATION_FAILED(422),
    MODEL_ENDPOINT_NOT_FOUND(422), MODEL_PROVIDER_REQUEST_REJECTED(422), MODEL_PROVIDER_RATE_LIMITED(429),
    MODEL_PROVIDER_UNAVAILABLE(502), MODEL_NETWORK_UNAVAILABLE(502), MODEL_RUNTIME_BUSY(429), MODEL_CALL_CANCELLED(409);

    private final int status;
    ModelAccessErrorCode(int status) { this.status = status; }
    @Override public String code() { return name(); }
    @Override public int status() { return status; }
}
