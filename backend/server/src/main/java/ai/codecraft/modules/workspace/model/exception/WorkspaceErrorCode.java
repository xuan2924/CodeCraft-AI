package ai.codecraft.modules.workspace.model.exception;

import ai.codecraft.common.exception.ErrorCode;

public enum WorkspaceErrorCode implements ErrorCode {
    CURSOR_EXPIRED(409), STREAM_CAPACITY(429), INVALID_REQUEST(400), RESOURCE_NOT_FOUND(404), TEST_HISTORY_PRUNED(410), EXERCISE_DELETED(404), HISTORY_LIMIT_REACHED(409), ACTIVE_EXERCISE_EXISTS(409),
    INVALID_STATE(409), IDEMPOTENCY_CONFLICT(409), PUBLICATION_CONFLICT(409),
    REVISION_CONFLICT(409), WORKSPACE_UNAVAILABLE(503), CONTROL_HELD(409), STALE_CONTROL(409),
    CONTROL_TRANSITION_PENDING(409), EXERCISE_EXPIRED(409), PATH_FORBIDDEN(403), WORKSPACE_CAPACITY(429), STORAGE_BUDGET_EXCEEDED(429), DELETION_RETRY_THROTTLED(429), STORAGE_METER_UNAVAILABLE(503),
    FILE_EXISTS(409), FILE_NOT_FOUND(404), WRITE_NOT_COMMITTED(409), TEST_SLOT_BUSY(409), TEST_TARGET_UNAVAILABLE(409);

    private final int status;
    WorkspaceErrorCode(int status) { this.status = status; }
    @Override public String code() { return name(); }
    @Override public int status() { return status; }
}
